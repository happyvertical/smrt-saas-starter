import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const repoRoot = dirname(dirname(packageRoot));
const generatedRoot = join(packageRoot, "generated");
const kotlinOut = join(generatedRoot, "kotlin/com/happyvertical/starter/Contract.kt");
const appKotlinOut = join(
  repoRoot,
  "apps/mobile/shared/src/commonMain/kotlin/generated/Contract.kt",
);
const appSwiftOut = join(repoRoot, "apps/mobile/iosApp/SmrtStarter/MobileContract.swift");
const jsonOut = join(generatedRoot, "mobile-contract.json");

await mkdir(dirname(kotlinOut), { recursive: true });
await mkdir(dirname(appKotlinOut), { recursive: true });
await mkdir(dirname(appSwiftOut), { recursive: true });

const source = await readFile(join(packageRoot, "src/index.ts"), "utf8");
const versionMatch = source.match(/mobileContractVersion = "([^"]+)"/);
if (!versionMatch) {
  throw new Error("Unable to find mobileContractVersion in src/index.ts");
}
const contractVersion = versionMatch[1];

const kotlinContract = `// Generated by packages/mobile-contract/scripts/generate-mobile-contract.mjs.
// Do not edit manually.
package com.happyvertical.starter

const val MobileContractVersion = "${contractVersion}"

data class MobileTenantSummary(
  val id: String,
  val name: String,
  val slug: String,
  val planName: String,
  val subscriptionStatus: String,
)

data class MobileTenantOption(
  val id: String,
  val name: String,
  val slug: String,
  val roleSlug: String,
  val roleLabel: String,
)

data class MobileUsageThreshold(
  val metricKey: String,
  val label: String,
  val used: Double,
  val limit: Double,
  val action: String,
  val state: String? = null,
  val allowed: Boolean? = null,
  val remaining: Double? = null,
)

data class MobileDashboardPayload(
  val tenant: MobileTenantSummary,
  val thresholds: List<MobileUsageThreshold>,
  val enabledFeatures: List<String>,
  val language: String,
)

data class MobileAuthProviderSummary(
  val id: String,
  val label: String,
  val type: String,
  val supportsPkce: Boolean,
)

data class MobileAuthStartRequest(
  val providerId: String? = null,
  val redirectUri: String,
  val scopes: List<String> = emptyList(),
  val state: String? = null,
  val loginHint: String? = null,
)

data class MobileAuthStartResponse(
  val providerId: String,
  val authorizationUrl: String,
  val state: String,
  val codeVerifier: String? = null,
  val nonce: String? = null,
  val redirectUri: String,
)

data class MobileAuthCompleteRequest(
  val providerId: String? = null,
  val code: String,
  val state: String? = null,
  val codeVerifier: String? = null,
  val redirectUri: String,
)

data class MobileUserSummary(
  val id: String,
  val email: String,
  val label: String,
)

data class MobileAuthSession(
  val accessToken: String,
  val tokenType: String,
  val expiresAt: String,
  val user: MobileUserSummary,
  val activeTenant: MobileTenantOption,
  val tenants: List<MobileTenantOption>,
)

data class MobileSessionBootstrap(
  val user: MobileUserSummary,
  val activeTenant: MobileTenantOption,
  val tenants: List<MobileTenantOption>,
  val dashboard: MobileDashboardPayload,
)

data class MobileDevicePermissionState(
  val status: String,
  val canRequest: Boolean,
  val reason: String? = null,
)

data class MobileDeviceCapability(
  val surface: String,
  val label: String,
  val supported: Boolean,
  val permission: MobileDevicePermissionState,
  val preferredInput: String,
)

data class MobileDeviceCapabilities(
  val camera: MobileDeviceCapability,
  val microphone: MobileDeviceCapability,
  val checkedAtEpochMillis: Long? = null,
)
`;

const swiftContract = `// Generated by packages/mobile-contract/scripts/generate-mobile-contract.mjs.
// Do not edit manually.
import Foundation

let MobileContractVersion = "${contractVersion}"

struct MobileTenantSummary {
  let id: String
  let name: String
  let slug: String
  let planName: String
  let subscriptionStatus: String
}

struct MobileTenantOption {
  let id: String
  let name: String
  let slug: String
  let roleSlug: String
  let roleLabel: String
}

struct MobileUsageThreshold {
  let metricKey: String
  let label: String
  let used: Double
  let limit: Double
  let action: String
  let state: String?
  let allowed: Bool?
  let remaining: Double?
}

struct MobileDashboardPayload {
  let tenant: MobileTenantSummary
  let thresholds: [MobileUsageThreshold]
  let enabledFeatures: [String]
  let language: String
}

struct MobileAuthProviderSummary {
  let id: String
  let label: String
  let type: String
  let supportsPkce: Bool
}

struct MobileAuthStartRequest {
  let providerId: String?
  let redirectUri: String
  let scopes: [String]
  let state: String?
  let loginHint: String?
}

struct MobileAuthStartResponse {
  let providerId: String
  let authorizationUrl: String
  let state: String
  let codeVerifier: String?
  let nonce: String?
  let redirectUri: String
}

struct MobileAuthCompleteRequest {
  let providerId: String?
  let code: String
  let state: String?
  let codeVerifier: String?
  let redirectUri: String
}

struct MobileUserSummary {
  let id: String
  let email: String
  let label: String
}

struct MobileAuthSession {
  let accessToken: String
  let tokenType: String
  let expiresAt: String
  let user: MobileUserSummary
  let activeTenant: MobileTenantOption
  let tenants: [MobileTenantOption]
}

struct MobileSessionBootstrap {
  let user: MobileUserSummary
  let activeTenant: MobileTenantOption
  let tenants: [MobileTenantOption]
  let dashboard: MobileDashboardPayload
}

struct MobileDevicePermissionState {
  let status: String
  let canRequest: Bool
  let reason: String?
}

struct MobileDeviceCapability {
  let surface: String
  let label: String
  let supported: Bool
  let permission: MobileDevicePermissionState
  let preferredInput: String
}

struct MobileDeviceCapabilities {
  let camera: MobileDeviceCapability
  let microphone: MobileDeviceCapability
  let checkedAtEpochMillis: Int64?
}
`;

await writeFile(kotlinOut, kotlinContract);
await writeFile(appKotlinOut, kotlinContract);
await writeFile(appSwiftOut, swiftContract);

await writeFile(
  jsonOut,
  JSON.stringify(
    {
      version: contractVersion,
      generatedAt: new Date(0).toISOString(),
      models: [
        "MobileTenantSummary",
        "MobileTenantOption",
        "MobileUsageThreshold",
        "MobileDashboardPayload",
        "MobileAuthProviderSummary",
        "MobileAuthStartRequest",
        "MobileAuthStartResponse",
        "MobileAuthCompleteRequest",
        "MobileUserSummary",
        "MobileAuthSession",
        "MobileSessionBootstrap",
        "MobileDevicePermissionState",
        "MobileDeviceCapability",
        "MobileDeviceCapabilities",
      ],
    },
    null,
    2,
  ),
);

console.log(`Generated mobile contract in ${generatedRoot}, ${appKotlinOut}, and ${appSwiftOut}`);
